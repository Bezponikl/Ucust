    def __init__(self, tavily_api_key: Optional[str] = None):
        self.api_key = tavily_api_key or os.getenv("TRAVITY_API_KEY", "")

    def get_calendar_events(
        self,
        country: str = "Россия",
        city: str = "Москва",
        niche: str = "IT",
        start_date: Optional[datetime] = None,
        days_count: int = 30
    ) -> List[Dict[str, Any]]:
        """
        Возвращает список праздников и инфоповодов, выпадающих на заданный N-дневный период.
        """
        start = start_date or datetime.utcnow()
        country_clean = (country or "Россия").strip().lower()
        city_clean = (city or "Москва").strip().lower()
        niche_clean = (niche or "бизнес").strip().lower()

        events_found: List[Dict[str, Any]] = []

        for offset in range(days_count):
            curr_date = start + timedelta(days=offset)
            m, d = curr_date.month, curr_date.day
            day_number = offset + 1
            date_str = curr_date.strftime("%Y-%m-%d")

            # 1. Проверка общих праздников СНГ
            if (m, d) in self.CIS_GENERAL_HOLIDAYS:
                h_info = self.CIS_GENERAL_HOLIDAYS[(m, d)]
                events_found.append({
                    "day_number": day_number,
                    "date": date_str,
                    "type": "cis_general_holiday",
                    "title": h_info["title"],
                    "vibe": h_info["vibe"],
                    "description": f"Общепризнанный праздник '{h_info['title']}' во всех странах СНГ."
                })

            # 2. Проверка государственных праздников страны
            country_holidays = self.COUNTRY_STATE_HOLIDAYS.get(country_clean, {})
            if (m, d) in country_holidays:
                h_info = country_holidays[(m, d)]
                events_found.append({
                    "day_number": day_number,
                    "date": date_str,
                    "type": "state_holiday",
                    "country": country.capitalize(),
                    "title": h_info["title"],
                    "vibe": h_info["vibe"],
                    "description": f"Государственный праздник {country.capitalize()}: {h_info['title']}."
                })

            # 3. Проверка Дня города
            if city_clean in self.CITY_DAYS and self.CITY_DAYS[city_clean] == (m, d):
                city_name = city.capitalize()
                events_found.append({
                    "day_number": day_number,
                    "date": date_str,
                    "type": "city_day",
                    "city": city_name,
                    "title": f"День города {city_name}",
                    "vibe": f"Гордость за родной город {city_name}, поздравление горожан, праздничные подарки",
                    "description": f"Главный праздник города {city_name}."
                })

            # 4. Проверка профессиональных праздников ниши
            for prof_group in self.PROFESSIONAL_HOLIDAYS:
                if any(kw in niche_clean for kw in prof_group["keywords"]):
                    if (m, d) in prof_group["dates"]:
                        h_info = prof_group["dates"][(m, d)]
                        events_found.append({
                            "day_number": day_number,
                            "date": date_str,
                            "type": "niche_professional_holiday",
                            "niche": niche,
                            "title": h_info["title"],
                            "vibe": h_info["vibe"],
                            "description": f"Профессиональный отраслевой праздник в нише {niche}: {h_info['title']}."
                        })

        logger.info(f"[EventHolidayCollector] Найдено {len(events_found)} праздников/инфоповодов для {city}, {country} на {days_count} дней.")
        return events_found

    async def fetch_city_and_national_events(self, city: str, country: str = "Россия") -> List[Dict[str, Any]]:
        """Совместимость со старым интерфейсом."""
        return self.get_calendar_events(country=country, city=city, niche="бизнес", days_count=30)
