    @classmethod
    def find_curated_fact(cls, text: str) -> Optional[Dict[str, Any]]:
        """Ищет совпадение объекта в верифицированной базе знаний."""
        text_lower = text.lower()
        for key, data in cls.OBJECT_ENCYCLOPEDIA.items():
            if key in text_lower:
                return data
        return None

    @classmethod
    async def extract_object_story_async(
        cls,
        topic: str,
        niche: str,
        company_name: str = ""
    ) -> Dict[str, Any]:
        """
        Извлекает историю и интересные факты об объекте из базы знаний или через Tavily Search.
        """
        # 1. Поиск в локальной базе шедевров
        matched = cls.find_curated_fact(f"{topic} {niche}")
        
        if matched:
            story_block = (
                f"🏛️ <b>ИСТОРИЯ И ТАЙНЫ ОБЪЕКТА: {matched['name']}</b>\n"
                f"• Происхождение: {matched['country']} ({matched['origin_year']})\n"
                f"• Легенда создания: {matched['origin_story']}\n"
                f"• Секретный факт: {matched['fun_fact']}\n"
                f"• Сенсорный акцент: {matched['sensory_hook']}"
            )
            return {
                "has_story": True,
                "source": "curated_encyclopedia",
                "object_name": matched["name"],
                "origin_story": matched["origin_story"],
                "fun_fact": matched["fun_fact"],
                "sensory_hook": matched["sensory_hook"],
                "formatted_story_prompt": story_block
            }

        # 2. Если в базе нет — динамический поиск через Tavily Web Search
        from skills.travity_search import TravitySearchSkill
        searcher = TravitySearchSkill()
        query = f"история создания {topic} интересные факты происхождение"
        
        try:
            web_results = await searcher.search(query)
            if web_results and "Результаты поиска не найдены" not in web_results:
                clean_snippet = re.sub(r'\[.*?\]\(.*?\)', '', web_results)[:350].strip()
                story_block = (
                    f"🏛️ <b>ИСТОРИЧЕСКИЙ ФАКТ И КОНТЕКСТ ТЕМЫ «{topic}»</b>\n"
                    f"{clean_snippet}"
                )
                return {
                    "has_story": True,
                    "source": "tavily_web_search",
                    "object_name": topic,
                    "origin_story": clean_snippet,
                    "fun_fact": "Подтвержденный факт из открытых профильных источников.",
                    "sensory_hook": f"Уникальная эстетика и проверенные временем традиции в {niche}.",
                    "formatted_story_prompt": story_block
                }
        except Exception as e:
            logger.warning("Ошибка поиска факта об объекте: %s", e)

        # 3. Fallback общий культурный контекст
        return {
            "has_story": False,
            "source": "fallback",
            "object_name": topic,
            "origin_story": f"Традиции мастерства и бережный подход команды «{company_name}».",
            "fun_fact": f"Каждая деталь в «{company_name}» создается с соблюдением высших стандартов.",
            "sensory_hook": "Безупречный визуальный стиль и приятные тактильные ощущения.",
            "formatted_story_prompt": ""
        }

